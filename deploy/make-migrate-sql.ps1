# Regenerates deploy\migrate.sql: every EF Core migration as one idempotent script for SSMS.
#
#   Run from the repository root after adding a migration:   .\deploy\make-migrate-sql.ps1
#
# Why not just `dotnet ef migrations script --idempotent`? That output puts each migration in one
# SQL batch, and SQL Server compiles a whole batch before running any of it. A statement that
# uses a column added earlier in the same migration then fails with "Invalid column name"
# (Msg 207): `AddSubjectHours` adds [Hours] and then updates it, for example. When the app
# migrates itself, EF runs each statement separately, so the app never hits this, but the script
# does. This wraps every statement in EXEC(N'...'), so each one is compiled only when it runs,
# after the statements before it have changed the schema. EF already does the same for some
# statement kinds.

$ErrorActionPreference = 'Stop'
$deploy = $PSScriptRoot
$root = Split-Path $deploy -Parent
$target = Join-Path $deploy 'migrate.sql'
$raw = Join-Path ([System.IO.Path]::GetTempPath()) "sengen-migrate-$([guid]::NewGuid().ToString('N')).sql"

# Release configuration: Visual Studio's running Debug instance locks bin\Debug.
# dotnet writes NuGet/model warnings to stderr, which Windows PowerShell 5.1 can turn into a
# terminating error under 'Stop'. Judge the run by its exit code instead.
$ErrorActionPreference = 'Continue'
dotnet ef migrations script --idempotent --project (Join-Path $root 'SENGENSystem.Server') --configuration Release --output $raw
$exit = $LASTEXITCODE
$ErrorActionPreference = 'Stop'
if ($exit -ne 0 -or -not (Test-Path $raw)) { throw 'dotnet ef migrations script failed.' }

$text = [System.IO.File]::ReadAllText($raw).Replace("`r`n", "`n")
Remove-Item $raw -Force

# One block per statement:
#   IF NOT EXISTS (SELECT * FROM [__EFMigrationsHistory] WHERE [MigrationId] = N'...')
#   BEGIN
#       <statement>
#   END;
# followed by a blank line and the next block or the migration's COMMIT.
$header = "IF NOT EXISTS \(\n    SELECT \* FROM \[__EFMigrationsHistory\]\n    WHERE \[MigrationId\] = N'[^']+'\n\)\nBEGIN\n"
$blockPattern = "(?s)(?<head>$header)(?<body>.*?)(?<tail>\nEND;\n)(?=\n(?:IF NOT EXISTS \(|COMMIT;))"
$expected = ([regex]::Matches($text, $header)).Count
$wrapped = 0
$text = [regex]::Replace($text, $blockPattern, {
    param($m)
    $script:wrapped++
    $body = $m.Groups['body'].Value
    $m.Groups['head'].Value + "    EXEC(N'" + $body.Replace("'", "''") + "');" + $m.Groups['tail'].Value
})
if ($wrapped -ne $expected -or $expected -eq 0) {
    throw "Wrapped $wrapped of $expected statements - the EF script layout has changed; check $target by hand."
}

$intro = @'
/*
    SEN-GEN database schema: every EF Core migration, as one idempotent script.
    Generated by deploy\make-migrate-sql.ps1. Don't edit by hand; rerun that script instead.

    HOW TO RUN (SSMS 2022)
      1. Connect to sql1003.site4now.net with SQL Server Authentication
         (login db_ad16f0_sengendb_admin). On the Connection Properties tab, set
         Encryption = Mandatory and leave "Trust server certificate" unticked.
      2. In the toolbar's database dropdown, select db_ad16f0_sengendb.
         This script has no USE statement, so it runs against whatever database is selected.
      3. Open this file and press Execute (F5). It takes under a minute.

    SAFE TO RE-RUN. Each migration checks __EFMigrationsHistory and is skipped if it is already
    applied, and each one runs in its own transaction. Running it after the app has migrated
    itself does nothing.

    WHAT IT DOES NOT DO: it creates the tables only. The Super Admin and School Admin accounts,
    the system-parameters row and the STI programs are created by the app on its first start,
    from deploy\appsettings.Production.json.

    Each statement is wrapped in EXEC(N'...') so SQL Server compiles it only when it runs. See the
    comment at the top of deploy\make-migrate-sql.ps1 for why.
*/

-- Filtered indexes in this schema require QUOTED_IDENTIFIER ON. SSMS sets both by default;
-- they are stated here so the script also runs from tools that don't.
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

'@

$final = ($intro.Replace("`r`n", "`n") + $text.TrimStart([char]0xFEFF)).Replace("`n", "`r`n")
[System.IO.File]::WriteAllText($target, $final, (New-Object System.Text.UTF8Encoding($true)))
Write-Host "Wrote $target ($wrapped statements wrapped)." -ForegroundColor Green
