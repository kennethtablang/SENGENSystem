using ClassInsight.Server.Hubs;
using ClassInsight.Server.Services;
using ClassInsight.Shared;

var builder = WebApplication.CreateBuilder(args);

// ---- Configuration --------------------------------------------------------
var port = builder.Configuration.GetValue("ClassInsight:Port", Protocol.DefaultServerPort);
var roomName = builder.Configuration.GetValue("ClassInsight:RoomName", "Classroom");

// Teacher auth resolves FAIL-CLOSED. Unless the admin explicitly opts into open mode,
// the server always enforces a teacher code: the configured one, or — if none is set —
// a random code generated and printed to the console at startup.
var configuredCode = builder.Configuration.GetValue<string?>("ClassInsight:TeacherCode");
var allowOpenTeacherMode = builder.Configuration.GetValue("ClassInsight:AllowOpenTeacherMode", false);

var teacherCode = string.IsNullOrWhiteSpace(configuredCode) ? null : configuredCode!.Trim();
var openTeacherMode = false;
var teacherCodeAutoGenerated = false;

if (teacherCode is null)
{
    if (allowOpenTeacherMode)
    {
        openTeacherMode = true; // explicit, deliberate opt-out of teacher auth
    }
    else
    {
        teacherCode = Convert.ToHexString(
            System.Security.Cryptography.RandomNumberGenerator.GetBytes(8)); // 16 hex chars (64-bit)
        teacherCodeAutoGenerated = true;
    }
}

// Listen on every interface so LAN clients can reach us by IP.
builder.WebHost.UseUrls($"http://0.0.0.0:{port}");

// ---- Services -------------------------------------------------------------
builder.Services.AddSignalR(options =>
{
    options.MaximumReceiveMessageSize = 256 * 1024; // SDP blobs can be a few KB
    options.KeepAliveInterval = TimeSpan.FromSeconds(10);
    options.ClientTimeoutInterval = TimeSpan.FromSeconds(30);
});

builder.Services.AddSingleton(new ServerIdentity
{
    RoomName = roomName,
    Port = port,
    TeacherCode = teacherCode,
    OpenTeacherMode = openTeacherMode,
});
builder.Services.AddSingleton<RoomRegistry>();
builder.Services.AddSingleton<TeacherAuthThrottle>();
builder.Services.AddHostedService<DiscoveryBeaconService>();

// NOTE: no CORS policy is registered. The student agent and MAUI teacher app are
// native SignalR clients, for which CORS does not apply. If a browser-based teacher
// view is ever added, register CORS here with an explicit origin allowlist — never
// SetIsOriginAllowed(_ => true) combined with AllowCredentials().

var app = builder.Build();

// ---- Endpoints ------------------------------------------------------------
app.MapHub<ClassroomHub>(Protocol.HubPath);

var identity = app.Services.GetRequiredService<ServerIdentity>();
var registry = app.Services.GetRequiredService<RoomRegistry>();

// Lightweight status endpoint for health checks / manual verification.
app.MapGet("/", () => Results.Json(new
{
    service = "ClassInsight coordination server",
    serverId = identity.ServerId,
    room = identity.RoomName,
    protocolVersion = Protocol.Version,
    hubPath = Protocol.HubPath,
    discoveryPort = Protocol.DiscoveryPort,
    students = registry.StudentCount,
    teachers = registry.TeacherCount,
}));

app.Logger.LogInformation(
    "ClassInsight server \"{Room}\" ({Id}) listening on :{Port}, hub {Hub}",
    identity.RoomName, identity.ServerId, port, Protocol.HubPath);

if (openTeacherMode)
    app.Logger.LogWarning(
        "OPEN TEACHER MODE is explicitly enabled (ClassInsight:AllowOpenTeacherMode=true): " +
        "ANY device on the network can register as a teacher and view student screens.");
else if (teacherCodeAutoGenerated)
    app.Logger.LogWarning(
        "Teacher join code (auto-generated): {Code}  —  enter this in the teacher app to connect. " +
        "Set ClassInsight:TeacherCode for a fixed code.", teacherCode);
else
    app.Logger.LogInformation("Teacher registration requires the configured join code.");

app.Run();
