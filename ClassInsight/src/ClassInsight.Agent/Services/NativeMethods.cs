    /// <summary>The user signed in to <paramref name="sessionId"/>, or null (e.g. at the logon screen).</summary>
    public static string? GetSessionUserName(uint sessionId)
    {
        if (!WTSQuerySessionInformation(WTS_CURRENT_SERVER_HANDLE, sessionId, WTSUserName, out var buf, out _))
            return null;
        try
        {
            var name = Marshal.PtrToStringUni(buf);
            return string.IsNullOrWhiteSpace(name) ? null : name;
        }
        finally
        {
            WTSFreeMemory(buf);
        }
    }

